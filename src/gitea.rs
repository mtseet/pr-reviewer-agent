use anyhow::{Context, Result};
use reqwest::Client;
use serde::{Deserialize, Serialize};

// ─── Gitea API response types ───────────────────────────────────────────────

#[derive(Deserialize)]
pub struct GiteaPullRequest {
    pub id: i64,
    pub number: i64,
    pub title: String,
    pub html_url: String,
    pub state: String,
    pub base: GiteaBranch,
    pub head: GiteaBranch,
}

#[derive(Deserialize)]
#[allow(dead_code)]
pub struct GiteaBranch {
    pub label: String,
    #[serde(rename = "ref")]
    pub branch_ref: String,
}

#[derive(Deserialize)]
#[allow(dead_code)]
pub struct GiteaFileChange {
    pub filename: String,
    pub status: String,
    pub additions: i32,
    pub deletions: i32,
    pub patch: Option<String>,
}

// ─── Gitea review submission types ──────────────────────────────────────────

#[derive(Serialize)]
pub struct GiteaReviewComment {
    pub path: String,
    pub body: String,
    #[serde(skip_serializing_if = "is_zero")]
    pub new_position: i64,
}

fn is_zero(v: &i64) -> bool {
    *v == 0
}

#[derive(Serialize)]
pub struct GiteaReview {
    pub body: String,
    pub event: String,
    pub comments: Vec<GiteaReviewComment>,
}

// ─── Gitea client ───────────────────────────────────────────────────────────

pub struct GiteaClient {
    client: Client,
    token: String,
    owner: String,
    repo: String,
    base_url: String,
}

impl GiteaClient {
    pub fn new(token: String, owner: String, repo: String, base_url: String) -> Self {
        Self {
            client: Client::new(),
            token,
            owner,
            repo,
            base_url: base_url.trim_end_matches('/').to_string(),
        }
    }

    pub async fn fetch_pr(&self, pr_id: i64) -> Result<GiteaPullRequest> {
        let url = format!(
            "{}/api/v1/repos/{}/{}/pulls/{}",
            self.base_url, self.owner, self.repo, pr_id
        );
        let res = self
            .client
            .get(&url)
            .bearer_auth(&self.token)
            .send()
            .await?
            .error_for_status()
            .context("Failed to fetch PR")?;
        let pr: GiteaPullRequest = res.json().await?;
        Ok(pr)
    }

    pub async fn fetch_pr_files(&self, pr_id: i64) -> Result<Vec<GiteaFileChange>> {
        let url = format!(
            "{}/api/v1/repos/{}/{}/pulls/{}/files",
            self.base_url, self.owner, self.repo, pr_id
        );
        let res = self
            .client
            .get(&url)
            .bearer_auth(&self.token)
            .send()
            .await?
            .error_for_status()
            .context("Failed to fetch PR files")?;
        let files: Vec<GiteaFileChange> = res.json().await?;
        Ok(files)
    }

    pub async fn fetch_pr_diff(&self, pr_id: i64) -> Result<String> {
        let url = format!(
            "{}/api/v1/repos/{}/{}/pulls/{}.diff",
            self.base_url, self.owner, self.repo, pr_id
        );
        let res = self
            .client
            .get(&url)
            .bearer_auth(&self.token)
            .header("Accept", "text/plain")
            .send()
            .await?
            .error_for_status()
            .context("Failed to fetch PR diff")?;
        let diff_text = res.text().await?;
        Ok(diff_text)
    }

    pub async fn submit_review(
        &self,
        pr_id: i64,
        review: &crate::ai::AIReviewResponse,
    ) -> Result<()> {
        let comments: Vec<GiteaReviewComment> = review
            .issues
            .iter()
            .map(|issue| GiteaReviewComment {
                path: issue.path.clone(),
                body: format!("[{}] {}", issue.severity.to_uppercase(), issue.body),
                new_position: issue.line as i64,
            })
            .collect();

        let gitea_review = GiteaReview {
            body: format!(
                "## AI Review Summary\n\n{}\n\n---\n*Generated by AI PR Reviewer*",
                review.summary
            ),
            event: review.event.clone(),
            comments,
        };

        let url = format!(
            "{}/api/v1/repos/{}/{}/pulls/{}/reviews",
            self.base_url, self.owner, self.repo, pr_id
        );

        let res = self
            .client
            .post(&url)
            .bearer_auth(&self.token)
            .json(&gitea_review)
            .send()
            .await?;

        if !res.status().is_success() {
            let status = res.status();
            let body = res.text().await?;
            anyhow::bail!("Review submission failed ({}): {}", status, body);
        }

        Ok(())
    }
}   