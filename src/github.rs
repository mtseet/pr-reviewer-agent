use anyhow::{Context, Result};
use reqwest::Client;
use serde::{Deserialize, Serialize};

// ─── GitHub API response types ──────────────────────────────────────────────

#[derive(Deserialize)]
pub struct GithubPullRequest {
    pub title: String,
    pub html_url: String,
    pub state: String,
    pub base: GithubBranch,
    pub head: GithubBranch,
}

#[derive(Deserialize)]
#[allow(dead_code)]
pub struct GithubBranch {
    pub label: String,
    pub ref_name: String,
}

#[derive(Deserialize)]
#[allow(dead_code)]
pub struct GithubFileChange {
    pub filename: String,
    pub status: String,
    pub additions: i32,
    pub deletions: i32,
    pub patch: Option<String>,
}

// ─── GitHub review submission types ─────────────────────────────────────────

#[derive(Serialize)]
pub struct GithubReviewComment {
    pub path: String,
    pub body: String,
    pub line: i32,
    pub side: String,
}

#[derive(Serialize)]
pub struct GithubReview {
    pub body: String,
    pub event: String,
    pub comments: Vec<GithubReviewComment>,
}

// ─── GitHub client ──────────────────────────────────────────────────────────

pub struct GithubClient {
    client: Client,
    token: String,
    owner: String,
    repo: String,
}

impl GithubClient {
    pub fn new(token: String, owner: String, repo: String) -> Self {
        Self {
            client: Client::new(),
            token,
            owner,
            repo,
        }
    }

    fn url(&self, path: &str) -> String {
        format!("https://api.github.com/repos/{}/{}/{}", self.owner, self.repo, path)
    }

    pub async fn fetch_pr(&self, pr_id: i64) -> Result<GithubPullRequest> {
        let url = self.url(&format!("pulls/{}", pr_id));
        let res = self
            .client
            .get(&url)
            .bearer_auth(&self.token)
            .header("Accept", "application/vnd.github.v3+json")
            .send()
            .await?
            .error_for_status()
            .context("Failed to fetch PR")?;
        let pr: GithubPullRequest = res.json().await?;
        Ok(pr)
    }

    pub async fn fetch_pr_files(&self, pr_id: i64) -> Result<Vec<GithubFileChange>> {
        let url = self.url(&format!("pulls/{}/files", pr_id));
        let res = self
            .client
            .get(&url)
            .bearer_auth(&self.token)
            .header("Accept", "application/vnd.github.v3+json")
            .send()
            .await?
            .error_for_status()
            .context("Failed to fetch PR files")?;
        let files: Vec<GithubFileChange> = res.json().await?;
        Ok(files)
    }

    pub async fn fetch_pr_diff(&self, pr_id: i64) -> Result<String> {
        let url = self.url(&format!("pulls/{}", pr_id));
        let res = self
            .client
            .get(&url)
            .bearer_auth(&self.token)
            .header("Accept", "application/vnd.github.v3.diff")
            .send()
            .await?
            .error_for_status()
            .context("Failed to fetch PR diff")?;
        let diff_text = res.text().await?;
        Ok(diff_text)
    }

    pub async fn submit_review(
        &self,
        pr_id: i64,
        review: &crate::ai::AIReviewResponse,
    ) -> Result<()> {
        let comments: Vec<GithubReviewComment> = review
            .issues
            .iter()
            .map(|issue| GithubReviewComment {
                path: issue.path.clone(),
                body: format!("[{}] {}", issue.severity.to_uppercase(), issue.body),
                line: issue.line,
                side: "RIGHT".to_string(),
            })
            .collect();

        // Map AI event to GitHub event (GitHub uses APPROVE, not APPROVED)
        let event = match review.event.as_str() {
            "APPROVED" => "APPROVE".to_string(),
            other => other.to_string(),
        };   

        let github_review = GithubReview {
            body: format!(
                "## AI Review Summary\n\n{}\n\n---\n*Generated by AI PR Reviewer*",
                review.summary
            ),
            event,
            comments,
        };

        let url = self.url(&format!("pulls/{}/reviews", pr_id));
        let res = self
            .client
            .post(&url)
            .bearer_auth(&self.token)
            .header("Accept", "application/vnd.github.v3+json")
            .json(&github_review)
            .send()
            .await?;

        if !res.status().is_success() {
            let status = res.status();
            let body = res.text().await?;
            anyhow::bail!("Review submission failed ({}): {}", status, body);
        }

        Ok(())
    }
}   